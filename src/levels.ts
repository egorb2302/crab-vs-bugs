import type { ThemeName } from "./themes";

// Every level is a strip of 20x12 chunks (one chunk ≈ one screen), joined left to right.
// Rows may be written short — the parser pads them out with sky.
//
//   =  solid        $  coin        ^  spikes      ~  lava / water
//   >  bug          @  spawn       F  finish      -  rail: moving platform, horizontal
//                                                 |  rail: moving platform, vertical
//
// Jump budget: a full jump clears 3 tiles up or 4 tiles across, but not both. Must-do jumps
// stay at 2 up / 3 across; anything tighter belongs to an optional coin.
// `npm run levels` re-checks every map: widths, legend, patrol ranges, reachability.

export interface LevelDef {
  /** stable key for saved progress — never reuse or rename */
  id: string;
  name: string;
  theme: ThemeName;
  chunks: string[][];
}

